'use strict';
const assert=require('node:assert/strict');
const {normalize,load,append,matchupUrl,recordLabel}=require('../dashboard/linemate_review.js');
const base={kind:'ATS',subject:'Milwaukee Bucks',split:'LAST10',verdict:'UNCLEAR',wins:'3',losses:'6',pushes:'1',basis:'Example fixture: each game’s recorded closing spread',note:''};
assert.equal(recordLabel(normalize(base)),'ATS 3–6–1');
assert.throws(()=>normalize({...base,basis:''}),/sportsbook/);
assert.throws(()=>normalize({...base,wins:'2.5'}),/whole-number/);
assert.throws(()=>normalize({...base,losses:'-1'}),/whole-number/);
assert.throws(()=>normalize({...base,subject:''}),/team or player/);
const fixed={...base,kind:'LINE',basis:'Full-game spread',side:'COVER',line:'15.5',hits:'7',sample:'10'};
const line=normalize(fixed);
assert.equal(recordLabel(line),'COVER 15.5: 7/10 at this line');
assert.equal(line.wins,undefined); // Selected-line hits never become an ATS W/L record.
assert.throws(()=>normalize({...fixed,line:''}),/exact selected line/);
assert.throws(()=>normalize({...fixed,hits:11}),/Hits must not exceed/);
assert.throws(()=>normalize({...fixed,sample:0}),/positive sample/);
assert.equal(normalize({...fixed,line:0}).line,0);
assert.throws(()=>normalize({...base,kind:'CONTEXT'}),/Describe/);
assert.equal(normalize({...base,kind:'CONTEXT',note:'Check starting lineup'}).wins,undefined);
const data=new Map(),storage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)};
append(storage,base,'2026-11-10','MIL @ NYK','https://linemate.io/nba','2026-11-10T17:00:00Z');
append(storage,{...base,kind:'CONTEXT',note:'Review after lineup confirmation'},'2026-11-11','MIL @ NYK','https://linemate.io/nba');
assert.equal(load(storage).length,2);
assert.equal(load(storage).filter(r=>r.slate==='2026-11-10').length,1);
assert.equal(load(storage)[0].reviewed_at,'2026-11-10T17:00:00Z');
const saved=JSON.stringify([...data]);
assert.throws(()=>append(storage,{...fixed,hits:100},'2026-11-10','MIL @ NYK','x'));
assert.equal(JSON.stringify([...data]),saved);
const corrupt={getItem:()=>'{broken',setItem:()=>{throw Error('Must not overwrite corrupted notes');}};
assert.throws(()=>append(corrupt,base,'2026-11-10','MIL @ NYK','x'),SyntaxError);
assert.throws(()=>load({getItem:()=>{throw Error('Storage blocked');}}),/Storage blocked/);
const game={away:{abbr:'MIL'},home:{abbr:'NYK'}};
assert.equal(matchupUrl(game,'2026-11-10'),'https://linemate.io/nba/summary/20261110-MIL-NYK');
assert.equal(matchupUrl({away:{abbr:'OKC'},home:{abbr:'POR'}},'2026-11-10'),'https://linemate.io/nba/summary/20261110-OKL-POR');
assert.equal(matchupUrl(game,'invalid'),'https://linemate.io/nba');
assert.equal(matchupUrl({away:{abbr:'<script>'},home:{abbr:'NYK'}},'2026-11-10'),'https://linemate.io/nba');
console.log('Linemate reviews: validation, storage isolation, corruption protection and routing passed');
