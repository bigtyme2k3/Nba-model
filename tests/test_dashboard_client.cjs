'use strict';
const assert = require('node:assert/strict');
const {esc,numeric,fmt,odds,timeET,dayLabel,quoteFor,filterProps,groupedQuotes} = require('../dashboard/app.js');
assert.equal(timeET('2026-11-11T00:30:00Z'), '7:30 PM ET');
assert.equal(timeET('2026-07-01T00:30:00Z'), '8:30 PM ET');
assert.equal(dayLabel('2026-11-10'), 'Tue, Nov 10');
assert.equal(odds(104), '+104'); assert.equal(odds(-137), '-137');
assert.equal(fmt(null), '—'); assert.equal(numeric(0), true);
assert.equal(esc('<script>"&'), '&lt;script&gt;&quot;&amp;');
const offer=(side,line,price,book='draftkings')=>({side,line,odds:price,book_key:book});
const first={player:'Jalen Brunson',team:'NYK',opp:'MIL',game:'MIL @ NYK',stat:'THREES',direction:'OVER',line:2.5,gap:1,decision:'RESEARCH',offers:[offer('UNDER',2.5,-137),offer('OVER',2.5,104),offer('OVER',3.5,190),offer('OVER',2.5,-104,'fanduel')]};
const second={...first,player:'Another Player',stat:'PTS',gap:10,offers:[offer('UNDER',2.5,-110)]};
assert.equal(quoteFor(first).odds,104);
assert.equal(quoteFor(first,'fanduel').odds,-104);
assert.equal(quoteFor(second,'draftkings'),null);
const qualified={...first,decision:'BET',quote:offer('OVER',2.5,-110,'fanduel')};
assert.equal(quoteFor(qualified).odds,-110);
assert.equal(filterProps([first,second],{search:'brunson',stat:'THREES',book:'draftkings',direction:'OVER',game:'MIL @ NYK'}).length,1);
assert.equal(filterProps([first,second],{book:'draftkings'}).length,1);
assert.equal(filterProps([first,second],{decision:'BET'}).length,0);
const input=[first,{...first,player:'B Player',gap:2}];
assert.equal(filterProps(input,{stat:'THREES',sort:'gap'})[0].gap,2);
assert.equal(input[0],first);
assert.equal(filterProps([first,second],{sort:'gap'})[0].player,'Another Player');
const grouped=groupedQuotes(first.offers);
assert.equal(grouped.length,3);
assert.equal(grouped.find(q=>q.book_key==='draftkings'&&q.line===2.5).UNDER,-137);
assert.equal(grouped.find(q=>q.book_key==='draftkings'&&q.line===3.5).UNDER,undefined);
console.log('Dashboard client: 22 assertions passed');
